static void colchgsub(unsigned char** ppChgTime, unsigned char** ppChgCnt, color_change_data* pColortbl) {
  short cnt;
  PALETTEENTRY *pPalet, *pColtbl;
  int i;

  if ((char)--**ppChgTime < 0) {
    **ppChgTime = pColortbl->time;
    if ((cnt = **ppChgCnt + 1) >= pColortbl->tate) {
      cnt = 0;
    }

    **ppChgCnt = cnt;

    cnt *= pColortbl->yoko;
    pPalet = &lpcolorwk[pColortbl->adr];
    pColtbl = &pColortbl->colortbl[cnt];

    for (i = 0; i < pColortbl->yoko; ++i) {
      *pPalet++ = *pColtbl++;
    }
  }

  ++*ppChgTime;
  ++*ppChgCnt;
}
